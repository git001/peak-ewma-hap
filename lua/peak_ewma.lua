-- Peak EWMA load balancing for HAProxy, without any change to HAProxy.
--
-- Two actions:
--
--   http-request lua.peak_ewma_pick <backend> <choices>
--       compares <choices> distinct random servers of <backend> and stores
--       the name of the cheapest one in txn.pe_pick, for "use-server".
--       2 is the power of two choices; 0 (or at least the number of usable
--       servers) compares all of them, like leastconn does.
--
--   http-after-response lua.peak_ewma_record
--       updates the peak EWMA of the server that answered with the time to
--       the response headers (%Tr). A 502, 503 or 504 generated by HAProxy
--       for the server counts as a penalty sample; a request the client
--       aborted counts as nothing.
--
-- cost = peak_ewma(Tr) * (current sessions + pending + 1) / weight
--
-- The EWMA of each server lives in process-wide variables, so all the
-- threads share it (load the file with lua-load-per-thread):
--
--   proc.pe_v_<backend>_<server>   EWMA in microseconds
--   proc.pe_t_<backend>_<server>   time of the last update in milliseconds
--
-- (characters other than letters, digits and "_" replaced by "_")
--
-- The read-modify-write of these variables is not atomic: concurrent
-- updates may lose a sample, which is fine for an estimate.
--
-- Settings, from the environment of HAProxy:
--   PE_TAU_MS          decay time constant, default 10000 (Finagle)
--   PE_DEFAULT_RTT_MS  cost of a server without sample yet, default 10
--   PE_PENALTY_MS      sample for a failed response, default 30000
--   PE_REFRESH_MS      how often the server list is refreshed, default 1000

local function env_num(name, default)
	local v = tonumber(os.getenv(name) or "")
	if v == nil then
		return default
	end
	return v
end

local TAU_MS = env_num("PE_TAU_MS", 10000)
local DEFAULT_RTT_US = env_num("PE_DEFAULT_RTT_MS", 10) * 1000
local PENALTY_US = env_num("PE_PENALTY_MS", 30000) * 1000
local REFRESH_MS = env_num("PE_REFRESH_MS", 1000)

-- variable names only allow letters, digits, "_" and "."; server names
-- like "be-7" would make set_var fail silently
local function var_key(be, srv)
	return (be .. "_" .. srv):gsub("[^%w_]", "_")
end

local function now_ms()
	local t = core.now()
	return t.sec * 1000 + t.usec // 1000
end

-- EWMA of <key> decayed to <now>, or nil without sample
local function decayed(key, now)
	local v = core.get_var("proc.pe_v_" .. key)
	local ts = core.get_var("proc.pe_t_" .. key)
	if v == nil or ts == nil then
		return nil
	end
	return v * math.exp(-(now - ts) / TAU_MS)
end

core.register_action("peak_ewma_record", { "http-after-res" }, function(txn)
	local srv = txn.f:srv_name()
	if srv == nil or srv == "" then
		return
	end
	local key = var_key(txn.f:be_name(), srv)
	local tr = txn.f:res_timer_hdr()
	local sample
	if tr ~= nil and tr >= 0 then
		sample = tr * 1000
	else
		-- no server response: a penalty only for the errors HAProxy
		-- generates for the server (bad gateway, unavailable, timeout),
		-- not for a client that went away
		local st = txn.f:status()
		if st ~= 502 and st ~= 503 and st ~= 504 then
			return
		end
		sample = PENALTY_US
	end

	-- the stored value is blended with the weight of the elapsed time,
	-- which already accounts for the decay: decaying it first would
	-- decay it twice (Finagle does the same, see the core patch)
	local now = now_ms()
	local cur = core.get_var("proc.pe_v_" .. key)
	local ts = core.get_var("proc.pe_t_" .. key)
	local new
	if cur == nil or ts == nil or sample > cur then
		-- peak: a slower answer replaces the average at once
		new = sample
	else
		local w = math.exp(-(now - ts) / TAU_MS)
		new = cur + (sample - cur) * (1 - w)
	end
	txn:set_var("proc.pe_v_" .. key, math.floor(new))
	txn:set_var("proc.pe_t_" .. key, now)
end)

-- per-thread list of the usable servers of each backend
local lists = {}

local function usable(sv)
	if sv:get_weight() <= 0 or sv:is_draining() then
		return false
	end
	local st = sv:get_stats()["status"] or ""
	return st:sub(1, 2) == "UP" or st == "no check"
end

local function servers(be, now)
	local l = lists[be]
	if l ~= nil and now - l.ts < REFRESH_MS then
		return l.srv
	end
	local px = core.backends[be]
	local srv = {}
	if px ~= nil then
		for name, sv in pairs(px.servers) do
			if usable(sv) then
				srv[#srv + 1] = { name = name, sv = sv }
			end
		end
	end
	lists[be] = { ts = now, srv = srv }
	return srv
end

local function cost(be, e, now)
	local lat = decayed(var_key(be, e.name), now) or DEFAULT_RTT_US
	if lat < 1000 then
		lat = 1000
	end
	local inflight = e.sv:get_cur_sess() + e.sv:get_pend_conn()
	return lat * (inflight + 1) / e.sv:get_weight()
end

core.register_action("peak_ewma_pick", { "http-req" }, function(txn, be, choices)
	local now = now_ms()
	local srv = servers(be, now)
	local n = #srv
	if n == 0 then
		return
	end
	local k = math.tointeger(tonumber(choices)) or 2
	local pick = srv[1]
	if n == 1 then
		-- nothing to compare
	elseif k <= 0 or k >= n then
		-- all servers, from a random start so that ties are spread
		local start = math.random(n)
		local best
		pick = nil
		for o = 0, n - 1 do
			local e = srv[(start + o - 1) % n + 1]
			local c = cost(be, e, now)
			if best == nil or c < best then
				best, pick = c, e
			end
		end
	elseif k == 2 then
		local i = math.random(n)
		local j = math.random(n - 1)
		if j >= i then
			j = j + 1
		end
		pick = srv[i]
		if cost(be, srv[j], now) < cost(be, pick, now) then
			pick = srv[j]
		end
	else
		-- k distinct servers: partial Fisher-Yates shuffle of the indexes
		local idx = {}
		for i = 1, n do
			idx[i] = i
		end
		local best
		pick = nil
		for d = 1, k do
			local r = math.random(d, n)
			idx[d], idx[r] = idx[r], idx[d]
			local e = srv[idx[d]]
			local c = cost(be, e, now)
			if best == nil or c < best then
				best, pick = c, e
			end
		end
	end
	txn:set_var("txn.pe_pick", pick.name)
end, 2)
